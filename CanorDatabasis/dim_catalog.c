const char *canordb_dim_name(int id) {
  if (id < 1 || id > CANORDB_DIM_COUNT) return 0;
  return canordb_dim_names[id - 1];
}
static int stem_eq(const char *a, const char *b) {
  size_t i;
  for (i = 0; a[i] && b[i]; i++) {
    char ca = a[i]; char cb = b[i];
    if (ca >= 'a' && ca <= 'z') ca = (char)(ca - 'a' + 'A');
    if (cb >= 'a' && cb <= 'z') cb = (char)(cb - 'a' + 'A');
    if (ca != cb) return 0;
  }
  return a[i] == 0 && b[i] == 0;
}
int canordb_dim_lookup(const char *text) {
  int i; const char *s;
  if (!text || !text[0]) return 0;
  s = text;
  if ((s[0] == 'D' || s[0] == 'd') && (s[1] == 'I' || s[1] == 'i') && (s[2] == 'M' || s[2] == 'm') && s[3] == '_') s += 4;
  for (i = 0; i < CANORDB_DIM_COUNT; i++) if (stem_eq(s, canordb_dim_names[i])) return i + 1;
  return 0;
}
